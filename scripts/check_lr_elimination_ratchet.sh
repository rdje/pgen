#!/usr/bin/env bash
# LR-ELIMINATION-RATCHET — a grammar edit may not RAISE the number of left-recursive cycles the
# elimination pass declines. Tree: docs/tasks/ENGINE-UNIVERSAL-SERVICES.md (leaf `.50`(d)).
# Exits NONZERO on a rise. Called by scripts/check_doctrines.sh via .githooks/pre-commit (E3)+CI (E4).
#
# ⭐⭐ WHY THIS EXISTS — the founding measurement, and it is about SILENCE rather than about a number.
#   `--lint-grammar` classifies `left_recursion_unhandled` as a WARNING and exits 0 on it. An
#   unhandled cycle is not untidy: the runtime guard does not handle it, it REJECTS same-position
#   re-entry, so every derivation needing the recursion at the seed position becomes UNREACHABLE and
#   the grammar declares strictly more than its parser accepts — an UNDER-acceptance on the profiles
#   being released. MEASURED (`ENGINE-UNIVERSAL-SERVICES.50`): ONE `@profiles` tag — the tag
#   `--lint-grammar` itself DERIVES for `constant_cast` — moved SystemVerilog from
#   `left_recursion_unhandled=0` to **15** and `left_recursion_eliminated=4` to **3**, while
#   `profile_orphans` (the ERROR-class counter an operator would quote) went to 0 and the lint still
#   exited 0. The whole doctrine set stayed GREEN. Nothing in the repository read this counter.
#
# ⛔ GIT IS THE BASELINE — there is deliberately NO tracked baseline artifact.
#   The comparison is `staged content` vs `HEAD content` of the SAME file, so the ratchet cannot go
#   stale, needs no `--rebaseline` step, and has no identity block to verify. It also isolates the
#   GRAMMAR axis by construction: both sides are linted with the same binary, so a rise can only come
#   from the edit.
#
# ⛔⛔ AND IT BLOCKS RATHER THAN WARNS, WITH NO ENV ESCAPE. `SV-CORPUS-GRAD.13e.11` established the
#   rule this follows: a guard is safe to make blocking over its whole population exactly when the
#   FIX PRECEDES IT. `.50`(b) shipped that fix, and `left_recursion_unhandled` is **0** on all ten
#   grammars that generate a parser, so a blocking ratchet fires on nothing on day one. If a rise is
#   ever genuinely right, the remedy is a leaf that changes the pass or the grammar — the posture
#   `BASELINE-IDENTITY` took when it DELETED the env escape its first design needed. ⚠️ The one
#   grammar with survivors is `systemverilog_lrm_profiled_wrapper` (23), the LRM extraction harness
#   that has never generated a parser; it is NOT excluded, because the ratchet compares a file with
#   ITSELF and 23 → 23 is not a rise.
#
# ⭐ SHORT-CIRCUIT, so the common case costs one lint and not two: a staged grammar reading
#   `left_recursion_unhandled=0` cannot have RISEN into 0, so HEAD is never linted for it. Today that
#   is every shipping grammar.
#
# ⚠️ HONEST LIMIT, stated rather than discovered: this is staged-scope-aware on GRAMMARS, so an
#   ENGINE change that raises the counter without touching a grammar is NOT caught here. That axis
#   has its own controls — the elimination pass's unit tests assert
#   `detect_left_recursion(...).is_empty()` after rewriting, and `GENERATED-REPRODUCIBILITY` notices
#   when generated bytes move — but neither is a census of this counter. Widening to engine sources
#   would run two SV lints (~10 s) on a large share of commits; priced and declined here, and named
#   so the gap is visible rather than implied.
#
# ARCHETYPE: oracle (DOCTRINE_ENFORCEMENT.md §3) — it RE-EXECUTES the lint on both sides.
# CONTRACT (§4): exit code is the verdict; explains on stderr; deterministic; read-only;
# staged-scope-aware; path-agnostic; inert when out of scope.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1

HEADLINE="LR-ELIMINATION-RATCHET"
BIN="rust/target/debug/ast_pipeline"
WORK="rust/target/lr_elimination_ratchet"

note() { printf '%s: %s\n' "$HEADLINE" "$1" >&2; }
ok()   { printf '%s: %s\n' "$HEADLINE" "$1"; }

# `left_recursion_unhandled=N` from a grammar file, or empty when the grammar does not load.
# ⛔ Read from the instrument's own headline, never from the exit code: `--lint-grammar` exits
# nonzero on any ERROR-class finding, which is unrelated to this counter, and exits 0 on the very
# warning this doctrine exists for. The exit code answers a different question.
unhandled_of() {
  local grammar="$1" log="$2"
  "$BIN" "$grammar" --lint-grammar >"$log" 2>&1
  sed -n 's/.*left_recursion_unhandled=\([0-9][0-9]*\).*/\1/p' "$log" | head -1
}

if [ "${1:-}" = "--self-test" ]; then
  mkdir -p "$WORK/selftest"
  [ -x "$BIN" ] || { note "--self-test needs $BIN"; exit 2; }
  arms=0; passed=0
  # ARM 1 — the tracked SV grammar reads 0, so the short-circuit path is exercised on real input.
  arms=$((arms + 1))
  if [ "$(unhandled_of grammars/systemverilog.ebnf "$WORK/selftest/sv.log")" = 0 ]; then
    passed=$((passed + 1)); ok "arm 1 — the tracked systemverilog grammar reads left_recursion_unhandled=0"
  else
    note "arm 1 FAILED — the population is no longer at 0, so a blocking ratchet is not free"
  fi
  # ARM 2 — the RED arm: the one-annotation reproducer this doctrine was founded on must read > 0
  # WITHOUT the `.50`(b) repair. With the repair in the binary it reads 0, which is itself the
  # measurement that (b) works — so this arm asserts the READER, not the defect: a grammar whose
  # headline is missing must yield an empty reading rather than a silent 0.
  arms=$((arms + 1))
  printf 'not a grammar\n' > "$WORK/selftest/bogus.ebnf"
  if [ -z "$(unhandled_of "$WORK/selftest/bogus.ebnf" "$WORK/selftest/bogus.log")" ]; then
    passed=$((passed + 1)); ok "arm 2 — a grammar with no lint headline yields NO reading, never a silent 0"
  else
    note "arm 2 FAILED — an unloadable grammar must not be scored as 0 unhandled cycles"
  fi
  # ARM 3 — the comparison itself refuses a rise. Driven on synthetic readings so the arm tests THIS
  # script's arithmetic rather than the engine's.
  arms=$((arms + 1))
  before=0; after=15
  if [ "$after" -gt "$before" ]; then
    passed=$((passed + 1)); ok "arm 3 — a 0 -> 15 reading is classified as a RISE (the founding measurement)"
  else
    note "arm 3 FAILED — the rise comparison is inverted"
  fi
  ok "--self-test: arms=${passed}/${arms}"
  [ "$passed" = "$arms" ] || exit 1
  exit 0
fi

staged="$(git diff --cached --name-only --diff-filter=ACM 2>/dev/null \
          | grep -E '^grammars/.*\.ebnf$' || true)"
[ -n "$staged" ] || exit 0

mkdir -p "$WORK"
if [ ! -x "$BIN" ]; then
  note "NOT EVALUATED — $BIN is absent, so the lint cannot be run. That is a BUILD finding, larger"
  note "  than this gate measures, and it refuses to convert one into the other."
  exit 0
fi

fail=0
checked=0
for grammar in $staged; do
  [ -f "$grammar" ] || continue
  base="$(basename "$grammar")"
  after="$(unhandled_of "$grammar" "$WORK/${base}.after.log")"
  if [ -z "$after" ]; then
    note "NOT EVALUATED — '$grammar' does not LOAD, so it has no left-recursion reading. See $WORK/${base}.after.log"
    continue
  fi
  checked=$((checked + 1))
  # A grammar at 0 cannot have risen INTO 0, so HEAD is never linted for it. This is the whole
  # population today, which is what keeps the gate cheap.
  if [ "$after" = 0 ]; then
    printf '  %s: left_recursion_unhandled=0 (no rise possible)\n' "$grammar"
    continue
  fi
  if ! git cat-file -e "HEAD:$grammar" 2>/dev/null; then
    note "'$grammar' is NEW and already declares $after left-recursive cycle(s) the pass declined."
    note "  There is no HEAD version to ratchet against, so this is reported rather than compared:"
    note "  every such derivation is UNREACHABLE at the seed position, and the grammar then declares"
    note "  strictly more than its parser accepts."
    continue
  fi
  git show "HEAD:$grammar" > "$WORK/${base}"
  before="$(unhandled_of "$WORK/${base}" "$WORK/${base}.before.log")"
  if [ -z "$before" ]; then
    note "NOT EVALUATED — HEAD's '$grammar' does not LOAD, so there is no baseline to compare against."
    continue
  fi
  printf '  %s: left_recursion_unhandled %s -> %s\n' "$grammar" "$before" "$after"
  if [ "$after" -gt "$before" ]; then
    note "RISE — '$grammar' raises left_recursion_unhandled from $before to $after."
    note "  These cycles are served ONLY by the runtime guard, which REJECTS same-position re-entry,"
    note "  so every derivation needing the recursion at the seed position becomes UNREACHABLE and"
    note "  the grammar declares strictly more than its parser accepts."
    note "  Diagnose with:  ./$BIN $grammar --lint-grammar   and"
    note "                  PGEN_INDIRECT_LR_GATE_DUMP=1 ./$BIN $grammar --lint-grammar 2>&1 | grep indirect-lr-gate"
    note "  There is no env escape by design: fix the grammar, or fix the pass in an owning leaf."
    fail=1
  fi
done

[ "$fail" = 0 ] || exit 1
if [ "$checked" = 0 ]; then
  ok "NOT EVALUATED — no staged grammar produced a left-recursion reading"
else
  ok "OK — ${checked} staged grammar(s), none raising left_recursion_unhandled"
fi
exit 0
